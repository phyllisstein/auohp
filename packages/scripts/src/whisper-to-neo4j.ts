/**
 * Parse transcripts generated by OpenAI's Whisper model and seed a Neo4j
 * database. Transcript data is searchable at the level of the statement so that
 * the frontend can jump directly to the relevant point in a matching video.
 * Granular statement-level data is also expected to seed a knowledge graph.
 * Structured at the statement level, this, too, will intertwingle the
 * narratives of a wide slate of interviewees for a deep account of an event.
 *
 * Whisper data has already been segmented by speaker and broken into
 * caption-sized hunks. The natural-language processing model attempts to keep
 * from splitting entities across captions, but it's not perfect: be on the
 * lookout for a class of bugs in which, e.g., "Stop the Church" is split into
 * "Stop the" and "Church," across captions, and does not match as a phrase.
 *
 * Edits to the captions for correctness and style will be made against the data
 * model, from which the captions are generated. The data model is the source of
 * truth, and the captions are a derived artifact.
 */
async function seed({ data, date, interviewee, interviewNumber, speakers, videoURL }) {
    await neo4jDriver.executeQuery(
        // language=Cypher
        `
            MATCH (jim:Person {name: 'Jim Hubbard'})
            MATCH (sarah:Person {name: 'Sarah Schulman'})
            WITH jim, sarah
            CREATE (i:Interview {number: $interviewNumber, date: date($date), uid: $interviewUID, url: $interviewURL})
            CREATE (video:Video {url: $videoURL, uid: $videoUID})
            CREATE (interviewee:Person {name: $interviewee, uid: $intervieweeUID})
            CREATE (sarahSpeaker:Speaker:Interviewer {label: $speakers.sarah})
            CREATE (jimSpeaker:Speaker:Interviewer {label: $speakers.jim})
            CREATE (intervieweeSpeaker:Speaker:Interviewee {label: $speakers.interviewee})
            MERGE (interviewee)-[:INTERVIEWED_AS]->(intervieweeSpeaker)
            MERGE (jim)-[:INTERVIEWED_AS]->(jimSpeaker)
            MERGE (sarah)-[:INTERVIEWED_AS]->(sarahSpeaker)
            CREATE (i)-[:INTERVIEWED_WITH]->(intervieweeSpeaker)
            CREATE (i)-[:INTERVIEWED_WITH]->(jimSpeaker)
            CREATE (i)-[:INTERVIEWED_WITH]->(sarahSpeaker)
            CREATE (i)-[:HAS_VIDEO]->(video)
        `, {
            date,
            interviewNumber: interviewNumber,

            interviewee,
            speakers,
            interviewUID: nanoid(),
            intervieweeUID: nanoid(),
            interviewURL: videoURL,

            videoUID: nanoid(),
            videoURL,
        },
    )

    for await (const segment of data.segments) {
        const result: EagerResult = await neo4jDriver.executeQuery(
            // language=Cypher
            `
                MATCH (speaker:Speaker {label: $speaker}) <-[:INTERVIEWED_WITH]- (interview:Interview {number: $interviewNumber})
                MATCH (speaker) <-[:INTERVIEWED_AS]- (person:Person)
                CREATE (statement:Statement {text: $text})
                MERGE (speaker)-[:SAYS {startTime: $startTime, endTime: $endTime}]->(statement)
                RETURN statement, person, interview
            `, {
                interviewNumber,
                speaker: segment.speaker,

                startTime: segment.start,
                endTime: segment.end,

                text: segment.text,
            },
        )

        if (!result?.records?.length) {
            console.error(`
                Could not create node for segment starting ${ segment.start } in interview
                ${ interviewNumber } for speaker ${ segment.speaker }.


                ${ JSON.stringify(result, null, 2) }
            `)
        }
    }
}

async function bootstrap() {
    await neo4jDriver.getServerInfo()

    await neo4jDriver.executeQuery(
        // language=Cypher
        `
          MATCH (n) DETACH DELETE n
        `,
    )

    await neo4jDriver.executeQuery(
    // language=Cypher
        `
          DROP INDEX transcript_search IF EXISTS
        `,
    )

    await neo4jDriver.executeQuery(
    // language=Cypher
        `
          DROP INDEX name_search IF EXISTS
        `,
    )

    for await (let label of NEO4J_LABELS) {
        await neo4jDriver.executeQuery(
            // language=Cypher
            `
                CREATE CONSTRAINT ${ label }UID IF NOT EXISTS
                FOR (n:${ label }) REQUIRE n.uid IS UNIQUE
            `,
            { label },
        )
    }

    await neo4jDriver.executeQuery(
        // language=Cypher
        `
            CREATE FULLTEXT INDEX transcript_search IF NOT EXISTS
            FOR (n:Statement) ON EACH [n.text]
        `)

    await neo4jDriver.executeQuery(
        // language=Cypher
        `
            CREATE (jim:Person {name: 'Jim Hubbard', uid: $jimUID})
            CREATE (sarah:Person {name: 'Sarah Schulman', uid: $sarahUID})
        `, { jimUID: nanoid(), sarahUID: nanoid() },
    )
}

